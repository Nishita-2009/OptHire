import json
import os

from agents.interview_evaluator.evaluator import (
    evaluate_answer,
    generate_final_interview_summary
)


# Maps the question categories from Agent 5
# to readable category names.
QUESTION_CATEGORIES = {
    "technical_questions": "Technical",
    "coding_questions": "Coding",
    "resume_based_questions": "Resume Based",
    "project_based_questions": "Project Based",
    "missing_skill_questions": "Missing Skill",
    "behavioral_questions": "Behavioral",
    "hr_questions": "HR"
}


def load_interview_questions():
    """
    Loads the interview questions generated by Agent 5.
    """

    file_path = "outputs/interview_questions.json"

    if not os.path.exists(file_path):
        raise FileNotFoundError(
            "interview_questions.json not found. "
            "Please run Agent 5 first."
        )

    with open(
        file_path,
        "r",
        encoding="utf-8"
    ) as file:

        interview = json.load(file)

    return interview


def collect_all_questions(interview: dict) -> list:
    """
    Collects all interview question categories
    into one ordered list.
    """

    all_questions = []

    for category_key, category_name in QUESTION_CATEGORIES.items():

        questions = interview.get(
            category_key,
            []
        )

        for question in questions:

            # Make a copy so the original Agent 5
            # interview data is not modified.
            question_copy = question.copy()

            question_copy["category"] = category_name

            all_questions.append(
                question_copy
            )

    return all_questions


def save_json(
    file_path: str,
    data
):
    """
    Saves Python data as formatted JSON.
    """

    os.makedirs(
        "outputs",
        exist_ok=True
    )

    with open(
        file_path,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            data,
            file,
            indent=4,
            ensure_ascii=False
        )


def run_interview():
    """
    Runs the interactive OptHire AI interview.
    """

    print("\n" + "=" * 60)

    print(
        "🤖 OPTHIRE AI INTERVIEW"
    )

    print("=" * 60)

    # -----------------------------------
    # Load Agent 5 interview questions
    # -----------------------------------

    interview = load_interview_questions()

    print(
        "\n✅ Interview questions loaded successfully"
    )

    # -----------------------------------
    # Collect all question categories
    # -----------------------------------

    questions = collect_all_questions(
        interview
    )

    total_generated_questions = len(
        questions
    )

    print(
        f"✅ Total questions generated by Agent 5: "
        f"{total_generated_questions}"
    )

    # ==================================================
    # TEMPORARY TEST MODE
    # ==================================================
    #
    # For the first test, we only ask 2 questions.
    #
    # This means:
    #
    # 2 answer evaluation API calls
    # +
    # 1 final summary API call
    # =
    # 3 Gemini API calls
    #
    # After Agent 6 works correctly,
    # REMOVE or COMMENT OUT the next line:
    #  
    # questions = questions[:2]
    # ==================================================

    print(
        f"\n🎯 Questions in this interview session: "
        f"{len(questions)}"
    )

    print(
        "\nInstructions:"
    )

    print(
        "- Read each question carefully."
    )

    print(
        "- Type your answer and press Enter."
    )

    print(
        "- Type 'quit' if you want to stop the interview."
    )

    print(
        "\nThe AI will evaluate every answer individually."
    )

    evaluations = []

    # -----------------------------------
    # Start asking questions
    # -----------------------------------

    for index, question in enumerate(
        questions,
        start=1
    ):

        print(
            "\n" + "-" * 60
        )

        print(
            f"Question {index}/{len(questions)}"
        )

        print(
            f"Question ID: "
            f"{question.get('question_id', 'N/A')}"
        )

        print(
            f"Category: "
            f"{question.get('category', 'N/A')}"
        )

        print(
            f"Difficulty: "
            f"{question.get('difficulty', 'N/A')}"
        )

        print(
            "\nQUESTION:"
        )

        print(
            question.get(
                "question",
                "Question not available."
            )
        )

        # -----------------------------------
        # Get candidate answer
        # -----------------------------------

        candidate_answer = input(
            "\nYour Answer: "
        ).strip()

        # -----------------------------------
        # Allow candidate to quit
        # -----------------------------------

        if candidate_answer.lower() == "quit":

            print(
                "\n⚠️ Interview stopped by candidate."
            )

            break

        # -----------------------------------
        # Handle empty answers
        # -----------------------------------

        if not candidate_answer:

            candidate_answer = (
                "No answer provided."
            )

        # -----------------------------------
        # Evaluate answer using Gemini
        # -----------------------------------

        print(
            "\n🤖 Evaluating your answer..."
        )

        evaluation = evaluate_answer(
            question=question,
            candidate_answer=candidate_answer
        )

        evaluations.append(
            evaluation
        )

        # -----------------------------------
        # Display evaluation
        # -----------------------------------

        score = evaluation.get(
            "score",
            0
        )

        rating = evaluation.get(
            "rating",
            "Not Available"
        )

        feedback = evaluation.get(
            "feedback",
            "No feedback available."
        )

        print(
            "\n✅ Answer Evaluated"
        )

        print(
            f"\nScore: {score}/100"
        )

        print(
            f"Rating: {rating}"
        )

        print(
            f"Feedback: {feedback}"
        )

    # -----------------------------------
    # Check whether any answers
    # were evaluated
    # -----------------------------------

    if not evaluations:

        print(
            "\n❌ No answers were evaluated."
        )

        print(
            "Interview ended without generating a summary."
        )

        return

    # -----------------------------------
    # Save individual evaluations
    # -----------------------------------

    evaluations_file = (
        "outputs/interview_evaluations.json"
    )

    save_json(
        evaluations_file,
        evaluations
    )

    print(
        "\n✅ Individual interview evaluations saved"
    )

    # -----------------------------------
    # Generate final interview summary
    # -----------------------------------

    print(
        "\n🤖 Generating final interview summary..."
    )

    final_summary = (
        generate_final_interview_summary(
            evaluations
        )
    )

    # -----------------------------------
    # Add interview statistics
    # -----------------------------------

    final_summary[
        "questions_generated"
    ] = total_generated_questions

    final_summary[
        "questions_answered"
    ] = len(evaluations)

    # -----------------------------------
    # Save final summary
    # -----------------------------------

    summary_file = (
        "outputs/interview_summary.json"
    )

    save_json(
        summary_file,
        final_summary
    )

    # -----------------------------------
    # Extract final result values
    # -----------------------------------

    overall_score = final_summary.get(
        "overall_interview_score"
    )

    performance = final_summary.get(
        "performance_level"
    )

    recommendation = final_summary.get(
        "recommendation"
    )

    # -----------------------------------
    # Display final interview result
    # -----------------------------------

    print(
        "\n" + "=" * 60
    )

    print(
        "✅ OPTHIRE AI INTERVIEW COMPLETED"
    )

    print(
        "=" * 60
    )

    print(
        f"\nOverall Score: "
        f"{overall_score}/100"
    )

    print(
        f"Performance: "
        f"{performance}"
    )

    print(
        f"Recommendation: "
        f"{recommendation}"
    )

    print(
        f"\nQuestions Answered: "
        f"{len(evaluations)}"
    )

    print(
        "\n📁 Detailed evaluations saved to:"
    )

    print(
        evaluations_file
    )

    print(
        "\n📁 Final interview summary saved to:"
    )

    print(
        summary_file
    )

    print(
        "\n🎉 Agent 6 completed successfully!"
    )


if __name__ == "__main__":

    run_interview()